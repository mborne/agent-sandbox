#!/usr/bin/env bash
set -euo pipefail

# Proxy entrypoint: generates the access rules for the mode chosen with
# SANDBOX_PROXY_MODE, then runs the stock ubuntu/squid entrypoint.
#
#   SANDBOX_PROXY_MODE=audit   ports 80/443 only, any destination (default)
#   SANDBOX_PROXY_MODE=strict  ports 80/443 and domains in allowed-domains.txt
#
# Usage (set in compose.yaml):
#   entrypoint: ["bash", "/etc/squid/sandbox/entrypoint.sh"]
#   command: ["-f", "/etc/squid/sandbox/squid.conf", "-NYC"]

mode="${SANDBOX_PROXY_MODE:-audit}"
rules=/etc/squid/sandbox-mode.conf

case "$mode" in
  audit)
    cat >"$rules" <<'CONF'
# Generated by entrypoint.sh: SANDBOX_PROXY_MODE=audit
http_access allow localnet
CONF
    ;;
  strict)
    cat >"$rules" <<'CONF'
# Generated by entrypoint.sh: SANDBOX_PROXY_MODE=strict
acl allowed_domains dstdomain "/etc/squid/sandbox/allowed-domains.txt"
http_access allow localnet allowed_domains
CONF
    ;;
  *)
    echo "entrypoint.sh: invalid SANDBOX_PROXY_MODE '$mode' (expected audit or strict)" >&2
    exit 1
    ;;
esac

echo "entrypoint.sh: proxy mode: $mode"
exec entrypoint.sh "$@"
